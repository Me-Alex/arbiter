  let lang = localStorage.getItem('arbiter.lang') || 'ro';
  function t(key) { return (dict[lang] && dict[lang][key]) || (dict.en[key]) || key; }
  function setLang(l) { lang = l; localStorage.setItem('arbiter.lang', l); apply(); }
  function apply() {
    document.documentElement.lang = lang;
    document.querySelectorAll('[data-i18n]').forEach((el) => {
      const k = el.getAttribute('data-i18n');
      el.textContent = t(k);
    });
    document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
      el.placeholder = t(el.getAttribute('data-i18n-placeholder'));
    });
    document.querySelectorAll('[data-i18n-title]').forEach((el) => {
      el.title = t(el.getAttribute('data-i18n-title'));
    });
    document.querySelectorAll('[data-i18n-aria-label]').forEach((el) => {
      el.setAttribute('aria-label', t(el.getAttribute('data-i18n-aria-label')));
    });
  }
  window.arbiterI18n = { t, setLang, apply, get lang() { return lang; } };
  document.addEventListener('DOMContentLoaded', apply);
